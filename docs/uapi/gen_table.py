"""Print the layout table of docs/UAPI.md from layout.inc, or check or update it.

    gen_table.py                 print the table
    gen_table.py --check FILE    fail unless FILE's table is the same
    gen_table.py --write FILE    replace FILE's table
"""

import pathlib
import re
import sys

BEGIN = "<!-- layout-table begin: generated by docs/uapi/gen_table.py -->"
END = "<!-- layout-table end -->"


def table():
    inc = pathlib.Path(__file__).with_name("layout.inc").read_text()
    structs = {}
    for name, size in re.findall(r"^STRUCT\((\w+), (\d+)\)$", inc, re.M):
        structs[name] = (int(size), [])
    for name, member, off, size in re.findall(
        r"^FIELD\((\w+), (\w+), (0x[0-9a-f]+), (\d+)\)$", inc, re.M
    ):
        structs[name][1].append((member, off, int(size)))
    for name, (size, members) in structs.items():
        end = 0
        for member, off, sz in members:
            if int(off, 16) != end:
                raise SystemExit(f"{name}.{member}: hole before offset {off}")
            end += sz
        if end != size:
            raise SystemExit(f"{name}: members end at {end}, size is {size}")
    header = pathlib.Path(__file__).with_name("powervr_sgx_drm.h").read_text()
    declared = set(re.findall(r"^struct (\w+) \{$", header, re.M))
    if declared != set(structs):
        raise SystemExit(f"header and layout.inc differ: {declared ^ set(structs)}")
    out = ["| struct | size | members: `offset name (size)` |", "|---|---|---|"]
    for name, (size, members) in structs.items():
        cells = ", ".join(f"`{off} {m} ({sz})`" for m, off, sz in members)
        out.append(f"| `{name}` | {size} | {cells} |")
    return "\n".join(out)


def main():
    if len(sys.argv) == 1:
        print(table())
        return 0
    mode, path = sys.argv[1], pathlib.Path(sys.argv[2])
    text = path.read_text()
    pattern = re.escape(BEGIN) + r"\n(?:.*?\n)?" + re.escape(END)
    block = f"{BEGIN}\n{table()}\n{END}"
    if mode == "--write":
        path.write_text(re.sub(pattern, lambda _: block, text, flags=re.S))
        return 0
    if block not in text:
        print(f"{path}: the layout table differs from layout.inc", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
