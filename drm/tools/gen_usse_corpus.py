"""
The uAPI test's corpus of valid USSE instructions (drm/tests/usse_corpus.h):
the clean-room isaspec encoder's words for its own test lists,

  mesa/src/sgx545/isa/tests/standalone.sh <mesa-tree> <out>
  <out>/sgx545_isa_test -t tests/gles2.txt tests/int.txt > words.txt
  gen_usse_corpus.py words.txt > drm/tests/usse_corpus.h

setl and savl are left out: valid encodings the validator refuses.
"""
import re
import sys

print('/* SPDX-License-Identifier: MIT */')
print('/* Copyright © 2026 Joseph Telaak */')
print('/* Generated by drm/tools/gen_usse_corpus.py from the isaspec encoder. Do not edit. */\n')
print('static const struct { uint32_t lo, hi; const char *text; } usse_corpus[] = {')
n = 0
for line in open(sys.argv[1]):
    m = re.match(r'^(.*?)\s*; ([0-9a-f]{8}) ([0-9a-f]{8})\s*$', line)
    if not m or line.startswith('#'):
        continue
    text = m.group(1).strip()
    if text.split()[0] in ('setl', 'savl'):
        continue
    print('\t{ 0x%s, 0x%s, "%s" },' % (m.group(2), m.group(3), text.replace('"', '\\"')))
    n += 1
print('};')
print('/* %d instructions */' % n)
