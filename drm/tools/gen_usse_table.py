"""
Generate the shader validator's USSE decode table (pvrsgx_usse_table.h) from
the isaspec description, mesa/src/sgx/isa/sgx.xml.

Every leaf bitset under #instruction becomes one (mask, match) pair: the bits
its own and its ancestors' <pattern>s fix. Fields, <assert>s and <override>s
don't take part, except the unused-source fields in PINNED, which are fixed at
the default the compilers emit: the validator accepts no more than that. A word
the kernel accepts must match exactly one leaf.

  gen_usse_table.py sgx.xml > pvrsgx_usse_table.h
"""
import sys
import xml.etree.ElementTree as ET

# Forms the validator treats specially, by isaspec leaf name.
KINDS = {
    'ldr': 'PVRSGX_USSE_LDR',	# register-file read (UAPI.md 7.2, D9)
    'str': 'PVRSGX_USSE_STR',	# register-file write
    'br': 'PVRSGX_USSE_BR',		# relative branch: target checked
    'setl': 'PVRSGX_USSE_SETL',	# link from a register: refused
    'savl': 'PVRSGX_USSE_SAVL',	# refused with setl
}


# Fields the description leaves free but only one value of which is ever
# emitted: rlp's unused src2 slot, 0x300 (ISA.md "unused2").
PINNED = {
    'U2N': 0x300 & 0x7f,
    'U2B': (0x300 >> 7) & 3,
    'U2E': 0x300 >> 9,
}


def field_bits(f):
    if f.get('pos') is not None:
        return int(f.get('pos')), int(f.get('pos'))
    return int(f.get('low')), int(f.get('high'))


def patterns(bs):
    mask = match = 0
    for f in bs.findall('field'):
        if f.get('name') not in PINNED:
            continue
        lo, hi = field_bits(f)
        width = hi - lo + 1
        mask |= ((1 << width) - 1) << lo
        match |= PINNED[f.get('name')] << lo
    for p in bs.findall('pattern'):
        bits = p.text.strip()
        if p.get('pos') is not None:
            lo = hi = int(p.get('pos'))
        else:
            lo, hi = int(p.get('low')), int(p.get('high'))
        if len(bits) != hi - lo + 1:
            raise SystemExit('pattern width mismatch in %s' % bs.get('name'))
        for i, c in enumerate(reversed(bits)):
            b = 1 << (lo + i)
            if c in '01':
                if mask & b:
                    raise SystemExit('bit %d fixed twice in %s' % (lo + i, bs.get('name')))
                mask |= b
                if c == '1':
                    match |= b
    return mask, match


def main():
    root = ET.parse(sys.argv[1]).getroot()
    sets = {bs.get('name'): bs for bs in root.findall('bitset')}
    parent = {n: bs.get('extends') for n, bs in sets.items()}
    children = {}
    for n, p in parent.items():
        children.setdefault(p, []).append(n)

    def chain(n):
        while n:
            yield n
            n = parent[n]

    leaves = []
    for n in sets:
        if n in children:
            continue
        anc = list(chain(n))
        if anc[-1] != '#instruction':
            continue	# operand hierarchies
        mask = match = 0
        for a in anc:
            m, v = patterns(sets[a])
            if mask & m:
                raise SystemExit('bit fixed twice along %s' % n)
            mask |= m
            match |= v
        leaves.append((n, mask, match))

    # Leaves must not overlap: a word matching two would be ambiguous.
    for i, (n1, m1, v1) in enumerate(leaves):
        for n2, m2, v2 in leaves[i + 1:]:
            common = m1 & m2
            if (v1 & common) == (v2 & common):
                raise SystemExit('%s and %s overlap' % (n1, n2))
    for name in KINDS:
        if name not in [l[0] for l in leaves]:
            raise SystemExit('no leaf %s' % name)

    leaves.sort(key=lambda l: (l[2] >> 59, l[0]))
    out = sys.stdout
    out.write('/* SPDX-License-Identifier: MIT */\n')
    out.write('/* Copyright © 2026 Joseph Telaak */\n\n')
    out.write('/*\n * Generated by drm/tools/gen_usse_table.py from mesa/src/sgx/isa/sgx.xml:\n')
    out.write(' * one (mask, match) per USSE form. Do not edit.\n */\n\n')
    out.write('/* %d forms */\n' % len(leaves))
    out.write('static const struct pvrsgx_usse_form pvrsgx_usse_forms[] = {\n')
    for n, m, v in leaves:
        kind = KINDS.get(n, 'PVRSGX_USSE_OK')
        out.write('\t{ 0x%016xull, 0x%016xull, %s },\t/* %s */\n' % (m, v, kind, n))
    out.write('};\n')


main()
