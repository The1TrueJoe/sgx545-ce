"""Generate the client command definitions of powervr_sgx_cmd.xml.

    gen_cmd.py header XML              the command block of powervr_sgx_drm.h
    gen_cmd.py kernel-h XML            pvrsgx_cmd_defs.h: the kernel's all-structs
    gen_cmd.py kernel-c XML            pvrsgx_cmd_defs.c: the check tables, per core
    gen_cmd.py doc XML                 the field table of docs/UAPI.md
    gen_cmd.py --check XML FILE...     fail unless each FILE's generated block is current
    gen_cmd.py --write XML FILE...     rewrite each FILE's generated block

FILE is powervr_sgx_drm.h (the header block) or a Markdown file (the doc table).
The schema and the rules are in the XML's header comment and in
docs/uapi/rev3-commands.md.
"""

import pathlib
import re
import sys
import textwrap
import xml.etree.ElementTree as ET

H_BEGIN = "/* BEGIN commands: generated by docs/uapi/gen_cmd.py from powervr_sgx_cmd.xml */"
H_END = "/* END commands */"
D_BEGIN = "<!-- cmd-table begin: generated by docs/uapi/gen_cmd.py -->"
D_END = "<!-- cmd-table end -->"

CHECKS = {"none", "range", "mask", "addr"}
TYPES = {"u32": ("__u32", 4), "s32": ("__s32", 4), "u64": ("__u64", 8), "f32": ("__u32", 4)}
HEAPS = {"client": "CLIENT", "pds_pixel": "PDS_PIXEL"}
LIMITS = {"tiles_x": "TILES_X", "tiles_y": "TILES_Y"}
EXTENTS = {"rt_depth": "RT_DEPTH", "rt_stencil": "RT_STENCIL", "pds_rows": "PDS_ROWS"}
CORE_VALUES = ("va_bits", "pds_row_bytes", "max_samples")
CHECK_ATTRS = ("min", "max", "max_limit", "mask", "heap", "align", "optional", "extent",
               "extent_field")
HEAD_SIZE = 16
EXT_HEAD_SIZE = 16
MAX_EXT_ID = 63


class GenError(Exception):
    pass


def num(s):
    return int(s, 0)


class Field:
    def __init__(self, el, owner):
        self.name = el.get("name")
        self.type = el.get("type")
        if self.type not in TYPES:
            raise GenError(f"{owner}.{self.name}: type {self.type!r}")
        self.ctype, self.size = TYPES[self.type]
        self.check = el.get("check", "none")
        if self.check not in CHECKS:
            raise GenError(f"{owner}.{self.name}: check {self.check!r}")
        self.doc = el.get("doc", "")
        self.attrs = {a: el.get(a) for a in CHECK_ATTRS if el.get(a) is not None}
        self.cores = {}
        for c in el.findall("core"):
            if c.get("absent"):
                raise GenError(f"{owner}.{self.name}: absent on {c.get('name')}: a field "
                               "some core lacks belongs in an extension")
            self.cores[c.get("name")] = {a: c.get(a) for a in CHECK_ATTRS if c.get(a) is not None}
        self.offset = None
        self.validate(owner)

    def validate(self, owner):
        a = self.attrs
        if self.check == "addr" and self.size != 8:
            raise GenError(f"{owner}.{self.name}: an address is a u64")
        if self.check == "range" and "max" not in a and "max_limit" not in a:
            raise GenError(f"{owner}.{self.name}: a range needs max or max_limit")
        if a.get("heap") and a["heap"] not in HEAPS:
            raise GenError(f"{owner}.{self.name}: heap {a['heap']!r}")
        if a.get("max_limit") and a["max_limit"] not in LIMITS:
            raise GenError(f"{owner}.{self.name}: max_limit {a['max_limit']!r}")
        ext = a.get("extent")
        if ext and ext not in EXTENTS:
            num(ext)
        if ext == "pds_rows" and not a.get("extent_field"):
            raise GenError(f"{owner}.{self.name}: pds_rows needs extent_field")

    def attrs_for(self, core):
        """The check attributes on a core, or None if one is unknown there."""
        a = dict(self.attrs)
        a.update(self.cores.get(core, {}))
        if any(v == "unknown" for v in a.values()):
            return None
        return a

    def describe(self, a):
        if a is None:
            return "unknown on this core"
        if self.check == "none":
            return "none"
        if self.check == "mask":
            return f"mask `{a['mask']}`"
        if self.check == "range":
            hi = a.get("max_limit") or a["max"]
            return f"{a.get('min', '0')}..{hi}"
        parts = ["address"]
        if a.get("heap"):
            parts.append(f"in {a['heap']}")
        if a.get("align"):
            parts.append(f"align {a['align']}")
        if a.get("optional") == "true":
            parts.append("0 = none")
        if a.get("extent"):
            e = a["extent"]
            parts.append(f"{a['extent_field']} rows mapped" if e == "pds_rows" else f"{e} mapped")
        return ", ".join(parts)


class Struct:
    """A command or an extension: its fields laid out after a 16-byte head."""

    def __init__(self, el, kind):
        self.kind = kind  # "command" or "extension"
        self.name = el.get("name")
        self.fields = [Field(f, self.name) for f in el.findall("field")]
        self.items = []  # (offset, Field or ("pad", size))
        self.lay_out()

    def lay_out(self):
        off = HEAD_SIZE
        for f in self.fields:
            if off % f.size:
                pad = f.size - off % f.size
                self.items.append((off, ("pad", pad)))
                off += pad
            f.offset = off
            self.items.append((off, f))
            off += f.size
        if off % 8:
            self.items.append((off, ("pad", 8 - off % 8)))
            off += 8 - off % 8
        self.size = off
        names = {f.name for f in self.fields}
        for f in self.fields:
            ef = f.attrs.get("extent_field")
            if ef and ef not in names:
                raise GenError(f"{self.name}.{f.name}: extent_field {ef} is not a field")


class Spec:
    def __init__(self, path):
        root = ET.parse(path).getroot()
        self.cores = []
        for c in root.findall("core"):
            vals = {v: c.get(v) for v in CORE_VALUES}
            if None in vals.values():
                raise GenError(f"core {c.get('name')}: needs {', '.join(CORE_VALUES)}")
            self.cores.append((c.get("name"), vals))
        core_names = [c for c, _ in self.cores]
        self.commands = [Struct(e, "command") for e in root.findall("command")]
        for c, e in zip(self.commands, root.findall("command")):
            c.job_type = e.get("job_type")
        cmd_names = [c.name for c in self.commands]
        self.exts = []
        seen = set()
        for e in root.findall("extension"):
            s = Struct(e, "extension")
            s.id = num(e.get("id"))
            s.command = e.get("command")
            s.ext_cores = e.get("cores", "").split()
            if not 1 <= s.id <= MAX_EXT_ID or s.id in seen:
                raise GenError(f"extension {s.name}: id {s.id} (1..{MAX_EXT_ID}, unique)")
            seen.add(s.id)
            if s.command not in cmd_names:
                raise GenError(f"extension {s.name}: command {s.command}")
            for c in s.ext_cores:
                if c not in core_names:
                    raise GenError(f"extension {s.name}: core {c}")
            self.exts.append(s)
        for f in self.all_fields():
            for c in f.cores:
                if c not in core_names:
                    raise GenError(f"{f.name}: core {c}")

    def all_fields(self):
        for s in self.commands + self.exts:
            yield from s.fields

    def exts_of(self, cmd):
        return [e for e in self.exts if e.command == cmd.name]

    def supported(self, core, vals, cmd):
        """Whether cmd is offered on core: every value it depends on is known."""
        for s in [cmd] + [e for e in self.exts_of(cmd) if core in e.ext_cores]:
            for f in s.fields:
                a = f.attrs_for(core)
                if a is None:
                    return False
                if f.check == "addr" and vals["va_bits"] == "unknown":
                    return False
                if a.get("extent") == "pds_rows" and vals["pds_row_bytes"] == "unknown":
                    return False
        return True


def u(name):
    return name.upper()


# ------------------------------------------------------------------ header


def comment_block(lines, indent=""):
    out = [f"{indent}/**"]
    out += [f"{indent} * {line}" if line else f"{indent} *" for line in lines]
    out.append(f"{indent} */")
    return out


def field_doc(name, doc):
    """A member's kernel-doc: one line if it fits in 100 columns, else wrapped."""
    one = f"\t/** @{name}: {doc} */"
    if len(one.expandtabs(8)) <= 100:
        return [one]
    lines = textwrap.wrap(f"@{name}: {doc}", 80 - 11)
    return ["\t/**"] + [f"\t * {line}" for line in lines] + ["\t */"]


def struct_c(cname, s, head_type, head_name, doc_lines):
    out = comment_block([f"struct {cname} - {doc_lines[0]}"] + doc_lines[1:])
    out.append(f"struct {cname} {{")
    out += [f"\t/** @{head_name}: The common head. */", f"\tstruct {head_type} {head_name};", ""]
    for off, it in s.items:
        if isinstance(it, tuple):
            out += [f"\t/** @_padding_{off:x}: Reserved. This field must be zero. */",
                    f"\t__u{it[1] * 8} _padding_{off:x};", ""]
            continue
        doc = it.doc + ("." if it.doc and not it.doc.endswith(".") else "")
        if it.type == "f32":
            doc += " IEEE-754 binary32 bits, any value."
        out += field_doc(it.name, doc.strip()) + [f"\t{it.ctype} {it.name};", ""]
    out[-1:] = ["};", ""]
    return out


def header(spec):
    out = [H_BEGIN, ""]
    out += comment_block([
        "struct drm_powervr_sgx_cmd_head - The head of every command struct",
        "",
        "The kernel copies a command as copy_struct_from_user() does: a shorter",
        "struct is zero-filled, non-zero bytes past what the kernel knows are",
        "-E2BIG. A field appended later takes 0 to mean \"absent\".",
    ])
    out += [
        "struct drm_powervr_sgx_cmd_head {",
        "\t/** @size: sizeof() the struct as the caller built it. */",
        "\t__u32 size;",
        "",
        "\t/** @_padding_4: Reserved. This field must be zero. */",
        "\t__u32 _padding_4;",
        "",
        "\t/**",
        "\t * @extensions: User pointer to the first &struct drm_powervr_sgx_ext,",
        "\t * or 0.",
        "\t */",
        "\t__u64 extensions;",
        "};",
        "",
    ]
    out += comment_block([
        "struct drm_powervr_sgx_ext - The head of every command extension",
        "",
        "At most 16 in a chain, each name once. A name of another command is",
        "-EINVAL; a name this core doesn't accept is -EOPNOTSUPP",
        "(%DRM_POWERVR_SGX_DEV_QUERY_COMMANDS_GET lists the accepted ones).",
    ])
    out += [
        "struct drm_powervr_sgx_ext {",
        "\t/** @name: One of the ``DRM_POWERVR_SGX_EXT_*`` names. */",
        "\t__u32 name;",
        "",
        "\t/** @_padding_4: Reserved. This field must be zero. */",
        "\t__u32 _padding_4;",
        "",
        "\t/** @next: User pointer to the next extension, or 0. */",
        "\t__u64 next;",
        "};",
        "",
    ]
    for e in spec.exts:
        cores = ", ".join(e.ext_cores)
        out.append(f"/* &struct drm_powervr_sgx_ext_{e.name.lower()}, for {cores} */")
        out.append(f"#define DRM_POWERVR_SGX_EXT_{u(e.name)} {e.id}")
    out.append("")
    for c in spec.commands:
        exts = ", ".join(f"&struct drm_powervr_sgx_ext_{e.name.lower()}" for e in spec.exts_of(c))
        out += struct_c(f"drm_powervr_sgx_cmd_{c.name}", c, "drm_powervr_sgx_cmd_head", "head",
                        [f"A {c.name.replace('_', ' ')} command",
                         *([""] + [f"Extensions: {exts}."] if exts else [])])
    for e in spec.exts:
        out += struct_c(f"drm_powervr_sgx_ext_{e.name.lower()}", e, "drm_powervr_sgx_ext", "base",
                        [f"Extension %DRM_POWERVR_SGX_EXT_{u(e.name)}",
                         "",
                         f"For &struct drm_powervr_sgx_cmd_{e.command}, on {', '.join(e.ext_cores)}.",
                         "Absent, its fields read as zero."])
    out.append(H_END)
    return "\n".join(out)


# ------------------------------------------------------------------ kernel


def kernel_h(spec):
    out = [
        "/* SPDX-License-Identifier: MIT */",
        "/* Copyright © 2026 Joseph Telaak */",
        "",
        "/* The per-core client-command tables, generated from the command description. */",
        "",
        "#ifndef PVRSGX_CMD_DEFS_H",
        "#define PVRSGX_CMD_DEFS_H",
        "",
        "#include \"pvrsgx_cmd.h\"",
        "",
        "enum pvrsgx_cmd_type {",
    ]
    out += [f"\tPVRSGX_CMD_{u(c.name)}," for c in spec.commands]
    out += ["\tPVRSGX_CMD_COUNT,", "};", ""]
    out.append("/* A command with every extension it can take on any core: absent ones zero. */")
    for c in spec.commands:
        out.append(f"struct pvrsgx_cmd_{c.name}_all {{")
        out.append(f"\tstruct drm_powervr_sgx_cmd_{c.name} base;")
        for e in spec.exts_of(c):
            out.append(f"\tstruct drm_powervr_sgx_ext_{e.name.lower()} {e.name.lower()};")
        out += ["};", ""]
    out.append("/* Extension name -> 1 + the command it belongs to, 0 for none. */")
    out.append(f"extern const u8 pvrsgx_cmd_ext_owner[{MAX_EXT_ID + 1}];")
    out.append("")
    for core, _ in spec.cores:
        out.append(f"extern const struct pvrsgx_cmd_core pvrsgx_cmd_core_{core};")
    out += ["", "#endif /* PVRSGX_CMD_DEFS_H */", ""]
    return "\n".join(out)


def field_entry(all_t, member, f, a):
    parts = [f".name = \"{f.name}\"",
             f".offset = offsetof(struct {all_t}, {member}.{f.name})",
             f".size = {f.size}"]
    if f.check != "none":
        parts.append(f".check = PVRSGX_CMD_CHECK_{u(f.check)}")
    if f.check == "range":
        parts.append(f".min = {a.get('min', '0')}")
        if a.get("max_limit"):
            parts.append(f".limit = PVRSGX_CMD_LIMIT_{LIMITS[a['max_limit']]}")
        else:
            parts.append(f".max = {a['max']}")
    elif f.check == "mask":
        parts.append(f".mask = {a['mask']}")
    elif f.check == "addr":
        parts.append(f".heap = PVRSGX_CMD_HEAP_{HEAPS[a.get('heap', 'client')]}")
        parts.append(f".align = {a.get('align', '1')}")
        if a.get("optional") == "true":
            parts.append(".optional = true")
        e = a.get("extent")
        if e in EXTENTS:
            parts.append(f".extent = PVRSGX_CMD_EXTENT_{EXTENTS[e]}")
            if e == "pds_rows":
                parts.append(f".extent_field = offsetof(struct {all_t}, "
                             f"{member}.{a['extent_field']})")
        elif e:
            parts.append(".extent = PVRSGX_CMD_EXTENT_BYTES")
            parts.append(f".extent_bytes = {e}")
    return ["\t{"] + [f"\t\t{p}," for p in parts] + ["\t},"]


def pad_entries(all_t, member, s):
    out = []
    for off, it in s.items:
        if isinstance(it, tuple):
            out += ["\t{", f"\t\t.name = \"_padding_{off:x}\",",
                    f"\t\t.offset = offsetof(struct {all_t}, {member}._padding_{off:x}),",
                    f"\t\t.size = {it[1]},", "\t\t.check = PVRSGX_CMD_CHECK_ZERO,", "\t},"]
    return out


def kernel_c(spec):
    out = [
        "// SPDX-License-Identifier: MIT",
        "/* Copyright © 2026 Joseph Telaak */",
        "",
        "/* The per-core client-command tables, generated from the command description. */",
        "",
        "#include <linux/array_size.h>",
        "#include <linux/build_bug.h>",
        "#include <linux/stddef.h>",
        "",
        "#include \"pvrsgx_cmd_defs.h\"",
        "",
        "/* The uAPI layout, pinned. */",
        "static_assert(PVRSGX_CMD_COUNT <= PVRSGX_CMD_TYPES_MAX);",
    ]
    for s, cname in [(c, f"drm_powervr_sgx_cmd_{c.name}") for c in spec.commands] + \
                    [(e, f"drm_powervr_sgx_ext_{e.name.lower()}") for e in spec.exts]:
        out.append(f"static_assert(sizeof(struct {cname}) == {s.size});")
        out.append(f"static_assert(sizeof(struct {cname}) % 8 == 0);")
        for f in s.fields:
            out.append(f"static_assert(offsetof(struct {cname}, {f.name}) == {f.offset});")
    out.append("")
    out.append(f"const u8 pvrsgx_cmd_ext_owner[{MAX_EXT_ID + 1}] = {{")
    for e in spec.exts:
        out.append(f"\t[DRM_POWERVR_SGX_EXT_{u(e.name)}] = 1 + PVRSGX_CMD_{u(e.command)},")
    out += ["};", ""]
    for core, vals in spec.cores:
        for c in spec.commands:
            all_t = f"pvrsgx_cmd_{c.name}_all"
            if not spec.supported(core, vals, c):
                out.append(f"/* {core}: {c.name} depends on a value not yet known there. */")
                out += [f"static const struct pvrsgx_cmd_def {core}_{c.name} = {{",
                        f"\t.name = \"{c.name}\",", f"\t.type = PVRSGX_CMD_{u(c.name)},", "};"]
                out.append("")
                continue
            out.append(f"static const struct pvrsgx_cmd_field {core}_{c.name}_fields[] = {{")
            for f in c.fields:
                out += field_entry(all_t, "base", f, f.attrs_for(core))
            out += pad_entries(all_t, "base", c)
            out += ["};", ""]
            exts = [e for e in spec.exts_of(c) if core in e.ext_cores]
            for e in exts:
                m = e.name.lower()
                out.append(f"static const struct pvrsgx_cmd_field {core}_{m}_fields[] = {{")
                for f in e.fields:
                    out += field_entry(all_t, m, f, f.attrs_for(core))
                out += pad_entries(all_t, m, e)
                out += ["};", ""]
            if exts:
                out.append(f"static const struct pvrsgx_cmd_ext_def {core}_{c.name}_exts[] = {{")
                for e in exts:
                    m = e.name.lower()
                    out += ["\t{", f"\t\t.id = DRM_POWERVR_SGX_EXT_{u(e.name)},",
                            f"\t\t.size = sizeof(struct drm_powervr_sgx_ext_{m}),",
                            f"\t\t.offset = offsetof(struct {all_t}, {m}),",
                            f"\t\t.fields = {core}_{m}_fields,",
                            f"\t\t.nr_fields = ARRAY_SIZE({core}_{m}_fields),", "\t},"]
                out += ["};", ""]
            out.append(f"static const struct pvrsgx_cmd_def {core}_{c.name} = {{")
            out.append(f"\t.name = \"{c.name}\",")
            out.append(f"\t.type = PVRSGX_CMD_{u(c.name)},")
            out.append("\t.supported = true,")
            out.append(f"\t.size = sizeof(struct drm_powervr_sgx_cmd_{c.name}),")
            out.append(f"\t.all_size = sizeof(struct {all_t}),")
            out.append(f"\t.fields = {core}_{c.name}_fields,")
            out.append(f"\t.nr_fields = ARRAY_SIZE({core}_{c.name}_fields),")
            if exts:
                out.append(f"\t.exts = {core}_{c.name}_exts,")
                out.append(f"\t.nr_exts = ARRAY_SIZE({core}_{c.name}_exts),")
            out += ["};", ""]
        out.append(f"const struct pvrsgx_cmd_core pvrsgx_cmd_core_{core} = {{")
        out.append(f"\t.name = \"{core}\",")
        for v in CORE_VALUES:
            unknown = 1 if v == "max_samples" else 0  # max_samples: unknown is 1x only
            out.append(f"\t.{v} = {unknown if vals[v] == 'unknown' else vals[v]},")
        out.append("\t.cmds = {")
        for c in spec.commands:
            out.append(f"\t\t[PVRSGX_CMD_{u(c.name)}] = &{core}_{c.name},")
        out += ["\t},", "};", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ doc


def doc(spec):
    cores = [c for c, _ in spec.cores]
    out = ["| struct | offset | field | type | " + " | ".join(cores) + " |",
           "|---|---|---|---|" + "---|" * len(cores)]
    for s in spec.commands + spec.exts:
        if s.kind == "command":
            title = f"`cmd_{s.name}` ({s.size} B)"
        else:
            title = f"`ext_{s.name.lower()}` ({s.size} B, id {s.id}, {' '.join(s.ext_cores)})"
        out.append(f"| {title} | 0x00 | head | | " + " | ".join("" for _ in cores) + " |")
        for f in s.fields:
            cells = []
            for core, vals in spec.cores:
                if s.kind == "extension" and core not in s.ext_cores:
                    cells.append("-")
                else:
                    cells.append(f.describe(f.attrs_for(core)))
            out.append(f"| | {f.offset:#04x} | `{f.name}` | {f.type} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("| core | " + " | ".join(CORE_VALUES) + " | commands offered |")
    out.append("|---|" + "---|" * (len(CORE_VALUES) + 1))
    for core, vals in spec.cores:
        offered = ", ".join(c.name for c in spec.commands if spec.supported(core, vals, c)) or "none"
        out.append(f"| {core} | " + " | ".join(vals[v] for v in CORE_VALUES) + f" | {offered} |")
    return "\n".join(out)


# ------------------------------------------------------------------ main


def blocks_for(path, spec):
    if path.suffix == ".h":
        return H_BEGIN, H_END, header(spec)
    return D_BEGIN, D_END, f"{D_BEGIN}\n{doc(spec)}\n{D_END}"


def main():
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    mode, xml = sys.argv[1], pathlib.Path(sys.argv[2])
    try:
        spec = Spec(xml)
    except GenError as e:
        print(f"{xml.name}: {e}", file=sys.stderr)
        return 1
    if mode == "header":
        print(header(spec))
    elif mode == "kernel-h":
        sys.stdout.write(kernel_h(spec))
    elif mode == "kernel-c":
        sys.stdout.write(kernel_c(spec))
    elif mode == "doc":
        print(doc(spec))
    elif mode in ("--check", "--write"):
        bad = 0
        for p in map(pathlib.Path, sys.argv[3:]):
            begin, end, block = blocks_for(p, spec)
            text = p.read_text()
            pattern = re.escape(begin) + r".*?" + re.escape(end)
            if not re.search(pattern, text, flags=re.S):
                print(f"{p}: no generated block ({begin})", file=sys.stderr)
                bad = 1
            elif mode == "--write":
                p.write_text(re.sub(pattern, lambda _: block, text, count=1, flags=re.S))
            elif block not in text:
                print(f"{p}: the generated block differs from {xml.name}", file=sys.stderr)
                bad = 1
        return bad
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
