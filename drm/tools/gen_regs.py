"""Generate drm/powervr_sgx/pvrsgx_regs.h from the GPL DDK's sgx545defs.h.

    gen_regs.py kernel/src/services4/srvkm/hwdefs/sgx545defs.h > drm/powervr_sgx/pvrsgx_regs.h

Only the registers and fields the driver uses are emitted, as offsets,
BIT() and GENMASK(). CI checks the committed header against this output.
"""

import re
import sys

# (register, [fields]) in the order they appear in the header. A field is the
# GPL name after EUR_CR_<register>_, without _MASK.
REGS = [
    ("CLKGATECTL", ["DPM_CLKG"]),
    ("CLKGATECTL2", []),
    ("CLKGATESTATUS", ["DPM_CLKS"]),
    ("CORE_ID", []),
    ("CORE_REVISION", []),
    ("SOFT_RESET", ["BIF_RESET", "DPM_RESET", "TA_RESET", "USE_RESET", "ISP_RESET",
                    "TSP_RESET"]),
    ("EVENT_HOST_ENABLE2", []),
    ("EVENT_HOST_CLEAR2", []),
    ("EVENT_STATUS2", []),
    ("EVENT_STATUS", ["MASTER_INTERRUPT", "TIMER", "SW_EVENT"]),
    ("EVENT_HOST_ENABLE", []),
    ("EVENT_HOST_CLEAR", ["MASTER_INTERRUPT", "SW_EVENT"]),
    ("TIMER", []),
    ("USE_CODE_BASE_0", []),
    ("PDS_EXEC_BASE", []),
    ("EVENT_KICKER", []),
    ("EVENT_KICK", ["NOW"]),
    ("EVENT_TIMER", []),
    ("EVENT_KICK2", ["NOW"]),
    ("BIF_CTRL", ["PAUSE", "INVALDC", "CLEAR_FAULT"]),
    ("BIF_INT_STAT", ["FAULT_REQ", "FAULT_TYPE", "FLUSH_COMPLETE"]),
    ("BIF_FAULT", []),
    ("BIF_DIR_LIST_BASE0", []),
    ("BIF_DIR_LIST_BASE1", []),
    ("BIF_BANK_SET", []),
    ("BIF_BANK0", ["INDEX_EDM", "INDEX_TA", "INDEX_HOST", "INDEX_3D", "INDEX_2D"]),
    ("BIF_MEM_REQ_STAT", ["READS"]),
]

# Fields spanning every 2-bit gating-mode field of a register.
UNIONS = [("CLKGATECTL", "_CLKG_MASK", "UNITS"), ("CLKGATECTL2", "_CLKG_MASK", "UNITS")]

HEAD = """/* SPDX-License-Identifier: GPL-2.0-only */
/* Copyright © 2026 Joseph Telaak */
/* Generated by drm/tools/gen_regs.py from the GPL DDK's sgx545defs.h: do not edit. */

#ifndef PVRSGX_REGS_H
#define PVRSGX_REGS_H

#include <linux/bits.h>

/*
 * SGX5xx core registers, from BAR offset 0. On a core nobody has initialised
 * only CLKGATECTL, CLKGATESTATUS, SOFT_RESET, EVENT_STATUS, EVENT_HOST_ENABLE,
 * BIF_CTRL, CORE_ID and CORE_REVISION are safe to read; some others hang the
 * bus until the reset sequence has run.
 */
"""

TAIL = """
#endif /* PVRSGX_REGS_H */
"""


def mask_expr(mask):
    lo = (mask & -mask).bit_length() - 1
    hi = mask.bit_length() - 1
    if mask != ((1 << (hi + 1)) - (1 << lo)):
        sys.exit(f"gen_regs: mask {mask:#x} is not contiguous")
    return f"BIT({lo})" if hi == lo else f"GENMASK({hi}, {lo})"


def line(name, value, indent=False):
    name = ("  " if indent else "") + name
    tabs = max(1, (48 - 8 - len(name) + 7) // 8)
    return f"#define {name}" + "\t" * tabs + value


def main():
    defs = {}
    for m in re.finditer(r"^#define\s+(EUR_CR_\w+)\s+(0x[0-9A-Fa-f]+|\d+)U?\b",
                         open(sys.argv[1]).read(), re.M):
        defs[m.group(1)] = int(m.group(2), 0)

    out = [HEAD.rstrip("\n")]
    for reg, fields in REGS:
        key = f"EUR_CR_{reg}"
        if key not in defs:
            sys.exit(f"gen_regs: {key} not in {sys.argv[1]}")
        out.append(line(f"SGX_CR_{reg}", f"0x{defs[key]:04x}"))
        for f in fields:
            mkey = f"{key}_{f}_MASK"
            if mkey not in defs:
                sys.exit(f"gen_regs: {mkey} not in {sys.argv[1]}")
            out.append(line(f"SGX_CR_{reg}_{f}", mask_expr(defs[mkey]), indent=True))
        for ureg, suffix, uname in UNIONS:
            if ureg != reg:
                continue
            mask = 0
            for k, v in defs.items():
                if k.startswith(f"{key}_") and k.endswith(suffix) and \
                   not k[len(key) + 1:].startswith(("2_", "STATUS")):
                    mask |= v
            out.append(line(f"SGX_CR_{reg}_{uname}", mask_expr(mask), indent=True))
    sys.stdout.write("\n".join(out) + "\n" + TAIL)


if __name__ == "__main__":
    main()
