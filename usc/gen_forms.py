"""Generate usse_forms.h, the C encoder's tables, from re/isa/hw.py.

    python3 -I usc/gen_forms.py > usc/usse_forms.h

hw.py (and its hw_*.py modules) is the one description of the USSE encoding:
every form's fixed bits, fields and operand slots, checked against libusc's
own encoder (re/isa/oracle.py) and the EA3. This script writes the same
tables as C data so the compiler encodes with exactly those layouts:

- one struct usse_form per hw.FORMS entry, in order; its enum name is the
  mnemonic hw.fmt() prints for the form with every field zero
  (USSE_FMAD, USSE_PCK_U8_F32, USSE_MOVC_Z_F32 = the f32 movc form);
- per field: the bit list, the stored default, and, for fields that only
  exist in some modes (hw.Fld.when), the one other field that switches it;
- per operand slot: number/bank/extension/modifier bits, the kind -> (bank,
  ext) table, format select and format control.

usse.c's usse_encode() is a port of hw.encode(); usc/check_enc.py runs both
over every corpus word.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ISA = os.path.join(HERE, "..", "re", "isa")
sys.path.insert(0, ISA)
import hw  # noqa: E402

KINDS = ["r", "o", "pa", "sa", "c", "g", "i", "#", "ix", "idx", "p"]
import hw_int  # noqa: E402
import hw_mem  # noqa: E402
import hw_pack  # noqa: E402

# slot types (usse.h enum usse_slot_type)
ST = {"Opd": 0, "COpd": 0, "SOpd": 0, "Imm": 1, "MoeVal": 2, "POpd": 3, "PredDst": 4, "SameBank": 5}


def cid(s):
    return re.sub(r"[^A-Za-z0-9]", "_", s).upper()


def bits(spec):
    return hw.bitlist(spec) if spec else []


def form_names():
    names, seen = [], {}
    for f in hw.FORMS:
        x = hw.decode(f.fval & 0xFFFFFFFF, f.fval >> 32)
        mn = hw.fmt(x).split()[0] if x is not None and x.form is f else f.name
        mn = mn.split(")")[-1]
        n = cid(mn)
        if n in seen:
            seen[n] += 1
            n = f"{n}_{seen[n]}"
        else:
            seen[n] = 0
        names.append(n)
    return names


def switch(f, fl):
    """-> (field name, op, k) for a conditional field or operand: present
    when field == k (op 0) or field != k (op 1)"""
    if not callable(getattr(fl, "when", None)):
        return None
    for o in [g.name for g in f.fields if g.name != getattr(fl, "name", None)]:
        on = {v for v in range(17) if fl.when({o: v})}
        if len(on) in (0, 17):
            continue
        if len(on) == 1:
            return o, 0, on.pop()
        if len(on) == 16:
            return o, 1, (set(range(17)) - on).pop()
    raise SystemExit(f"{f.name}.{getattr(fl, 'name', fl.role)}: can't tell what switches it")


def main():
    names = form_names()
    fields = sorted({fl.name for f in hw.FORMS for fl in f.fields})
    out = []
    w = out.append
    w("/* Generated by usc/gen_forms.py from re/isa/hw.py: do not edit. */")
    w("#ifndef USSE_FORMS_H\n#define USSE_FORMS_H\n")
    w("enum usse_form_id {")
    for n in names:
        w(f"   USSE_{n},")
    w("   USSE_NUM_FORMS\n};\n")
    w("enum usse_field_id {")
    for n in fields:
        w(f"   USSE_F_{cid(n)},")
    w("   USSE_NUM_FIELDS\n};\n")
    w("#endif /* USSE_FORMS_H */\n")
    w("#if defined(USSE_FORMS_TABLES) && !defined(USSE_FORMS_TABLES_DONE)")
    w("#define USSE_FORMS_TABLES_DONE\n")
    w("static const char *const usse_field_names[USSE_NUM_FIELDS] = {")
    w("   " + ", ".join(f'"{n}"' for n in fields))
    w("};\n")
    for i, f in enumerate(hw.FORMS):
        flds = []
        for fl in f.fields:
            b = bits(fl.spec)
            sw = switch(f, fl)
            dep, depop, depk = (f"USSE_F_{cid(sw[0])}", sw[1], sw[2]) if sw else ("-1", 0, 0)
            flds.append(f"{{USSE_F_{cid(fl.name)}, {len(b)}, {{{', '.join(map(str, b))}}}, "
                        f"{fl.default - fl.bias}, {fl.bias}, {dep}, {depop}, {depk}}}")
        w(f"static const struct usse_fld usse_flds_{i}[] = {{")
        for x in flds:
            w(f"   {x},")
        if not flds:
            w("   {0}")
        w("};")
        ops = []
        for o in f.ops:
            st = ST.get(type(o).__name__)
            if o.text or st is None:
                ops.append(None)
                continue
            enc = {}
            for (b, e), k in o.table.items():
                ks = ["c", "g"] if k == "cg" else [k]
                for kk in ks:
                    enc.setdefault(kk, (b, e))
            if st == 1 or st == 2:
                enc = {"#": (0, 0)}
            elif st == 3 or st == 4:
                enc = {"p": (0, 0)}
            elif st == 5:
                enc = {k: (0, 0) for k in hw_int.SameBank.KINDS}
            allowed = o.kinds
            tab = []
            for k in KINDS:
                if o.fixed_kind:
                    tab.append("0" if k == o.fixed_kind else "-1")
                elif k in enc and (not allowed or k in allowed):
                    b, e = enc[k]
                    tab.append(str(b << 1 | e))
                else:
                    tab.append("-1")

            def bl(spec):
                b = bits(spec)
                return f"{{{len(b)}, {{{', '.join(map(str, b))}}}}}"
            fc = -1 if o.fc is None else o.fc
            sw = switch(f, o)
            dep, depop, depk = (f"USSE_F_{cid(sw[0])}", sw[1], sw[2]) if sw else ("-1", 0, 0)
            extra = getattr(o, "flag", None) or getattr(o, "lane", None)
            ops.append(f"{{\"{o.role}\", {st}, {bl(o.num)}, {bl(o.bank)}, {bl(o.ext)}, {bl(o.neg)}, {bl(o.abs)}, "
                       f"{bl(extra)}, {{{', '.join(tab)}}}, {int(bool(o.fmt))}, {int(bool(o.half16))}, {fc}, "
                       f"{int(bool(getattr(o, 'fmtname', None)))}, {int(bool(getattr(o, 'signed', None)))}, "
                       f"{dep}, {depop}, {depk}}}")
        w(f"static const struct usse_slot usse_slots_{i}[] = {{")
        for x in ops:
            w(f"   {x or '{NULL}'},")
        if not ops:
            w("   {NULL}")
        w("};")
    w("\nstatic const struct usse_form usse_forms[USSE_NUM_FORMS] = {")
    for i, (f, n) in enumerate(zip(hw.FORMS, names)):
        w(f"   [USSE_{n}] = {{\"{f.name}\", 0x{f.fmask:016x}ull, 0x{f.fval:016x}ull, "
          f"{len(f.fields)}, usse_flds_{i}, {len(f.ops)}, usse_slots_{i}}},")
    w("};\n")
    w("#endif /* USSE_FORMS_TABLES */")
    print("\n".join(out))


if __name__ == "__main__":
    main()
