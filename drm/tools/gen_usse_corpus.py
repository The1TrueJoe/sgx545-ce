"""
The uAPI test's corpus of valid USSE instructions (drm/tests/usse_corpus.h):
the clean-room isaspec encoder's words for its own test lists,

  mesa/tests/isa-standalone/standalone.sh <mesa-tree> <out>
  <out>/sgx545_isa_test -t tests/gles2.txt tests/int.txt > words.txt
  gen_usse_corpus.py words.txt > drm/tests/usse_corpus.h

Words the validator refuses are left out: the forms gen_usse_table.py
refuses, br [link], phas.i with a target (it needs a mapped object), setfc
other than the program-start state and writes to c or g.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_usse_table import REFUSE  # noqa: E402


def refused(text):
    t = re.sub(r'^\(!?p\d\)\s*', '', text)
    op = t.split()[0]
    if op == 'phas.i':
        return not t.startswith('phas.i #0,')
    if op in REFUSE or op.split('.')[0] in REFUSE:
        return True
    if op == 'setfc':
        return not t.startswith('setfc #0, #1')
    if op == 'br' and 'link' in t:
        return True
    return re.match(r'^\S+ [cg]\d+,', t) is not None

print('/* SPDX-License-Identifier: MIT */')
print('/* Copyright © 2026 Joseph Telaak */')
print('/* Generated by drm/tools/gen_usse_corpus.py from the isaspec encoder. Do not edit. */\n')
print('static const struct { uint32_t lo, hi; const char *text; } usse_corpus[] = {')
n = 0
for line in open(sys.argv[1]):
    m = re.match(r'^(.*?)\s*; ([0-9a-f]{8}) ([0-9a-f]{8})\s*$', line)
    if not m or line.startswith('#'):
        continue
    text = m.group(1).strip()
    if refused(text):
        continue
    print('\t{ 0x%s, 0x%s, "%s" },' % (m.group(2), m.group(3), text.replace('"', '\\"')))
    n += 1
print('};')
print('/* %d instructions */' % n)
