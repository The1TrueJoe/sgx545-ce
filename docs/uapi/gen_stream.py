"""Generate the stream tables of powervr_sgx_kmd_stream.xml.

    gen_stream.py kernel-h XML PREFIX    kernel header: decoded structs, defs
    gen_stream.py kernel-c XML PREFIX    kernel source: the stream tables
    gen_stream.py user XML               userspace stream writer (Mesa side)
    gen_stream.py doc XML                the stream tables of docs/UAPI.md
    gen_stream.py --check XML UAPI.md    fail unless UAPI.md has that table
    gen_stream.py --write XML UAPI.md    replace UAPI.md's table

Mesa's csbgen reads the same XML; this script reads only what csbgen ignores
(streams, and the validation attributes on their fields). The rules for a
stream are in the XML's header comment and in docs/UAPI.md section 3.
"""

import pathlib
import re
import sys
import xml.etree.ElementTree as ET

BEGIN = "<!-- stream-table begin: generated by docs/uapi/gen_stream.py -->"
END = "<!-- stream-table end -->"

CHECKS = {"none", "range", "mask", "addr"}
HEAPS = {"client": "CLIENT", "pds_pixel": "PDS_PIXEL"}
LIMITS = {"tiles_x": "TILES_X", "tiles_y": "TILES_Y"}
EXTENTS = {"rt_depth": "RT_DEPTH", "rt_stencil": "RT_STENCIL", "rows16": "ROWS16"}
HDR_BYTES = 8


def num(s):
    return int(s, 0)


class Field:
    def __init__(self, stream, e):
        a = e.attrib
        self.name = a["name"]
        self.bits = int(a["size"])
        self.type = a["type"]
        self.check = a.get("check")
        where = f"{stream}.{self.name}"
        if self.bits not in (32, 64):
            raise SystemExit(f"{where}: only 32- and 64-bit fields")
        if self.check not in CHECKS:
            raise SystemExit(f"{where}: check must be one of {sorted(CHECKS)}")
        if (self.type == "address") != (self.check == "addr"):
            raise SystemExit(f"{where}: type address and check addr go together")
        if self.type == "address" and a.get("shift") != "0":
            raise SystemExit(f"{where}: addresses are byte addresses, shift 0")
        self.min = num(a.get("min", "0"))
        self.max = num(a["max"]) if "max" in a else (1 << self.bits) - 1
        self.limit = a.get("max_limit")
        self.mask = num(a.get("mask", "0"))
        self.align = num(a.get("align", "1"))
        self.heap = a.get("heap", "client")
        self.optional = a.get("optional") == "true"
        self.extent = a.get("extent")
        self.extent_field = a.get("extent_field")
        if self.limit is not None and self.limit not in LIMITS:
            raise SystemExit(f"{where}: unknown max_limit {self.limit}")
        if self.heap not in HEAPS:
            raise SystemExit(f"{where}: unknown heap {self.heap}")
        if self.check == "range" and self.min > self.max:
            raise SystemExit(f"{where}: min above max")
        if self.check == "mask" and "mask" not in a:
            raise SystemExit(f"{where}: check mask needs a mask")
        if self.align & (self.align - 1):
            raise SystemExit(f"{where}: align must be a power of two")
        if self.extent is not None and self.extent not in EXTENTS:
            num(self.extent)
        if (self.extent == "rows16") != (self.extent_field is not None):
            raise SystemExit(f"{where}: extent rows16 and extent_field go together")
        self.bytes = self.bits // 8
        self.offset = None  # in the stream, main streams only
        self.dest = None  # in the decoded struct

    def describe(self):
        """The kernel check, in words, for the doc table."""
        if self.check == "none":
            return "none: reaches a register only"
        if self.check == "range":
            hi = f"`{self.limit}` limit" if self.limit else str(self.max)
            return f"{self.min}..{hi}"
        if self.check == "mask":
            return f"bits in `{self.mask:#010x}` only"
        out = ["0 = none" if self.optional else "not 0", "below 2^32"]
        if self.heap != "client":
            out.append(f"in `{self.heap.upper()}`")
        if self.align > 1:
            out.append(f"{self.align}-byte aligned")
        if self.extent == "rows16":
            out.append(f"mapped for 16·`{self.extent_field}` bytes")
        elif self.extent in EXTENTS:
            out.append(f"mapped for `{self.extent}` bytes")
        elif self.extent is not None:
            out.append(f"mapped for {num(self.extent):#x} bytes")
        return "; ".join(out)


class Stream:
    def __init__(self, e):
        self.name = e.attrib["name"]
        self.length = int(e.attrib["length"])
        self.quirk = int(e.attrib.get("quirk", "0"))
        self.fields = [Field(self.name, f) for f in e.findall("field")]
        if sum(f.bits for f in self.fields) != 32 * self.length:
            raise SystemExit(f"{self.name}: length is not the fields' dwords")
        names = [f.name for f in self.fields]
        if len(set(names)) != len(names):
            raise SystemExit(f"{self.name}: a field is defined twice")
        for f in self.fields:
            if f.extent_field is not None:
                target = [g for g in self.fields if g.name == f.extent_field]
                if not target or target[0].bits != 32:
                    raise SystemExit(f"{self.name}.{f.name}: extent_field is not a 32-bit field here")


def parse(path):
    root = ET.parse(path).getroot()
    streams = [Stream(s) for s in root.findall("stream")]
    exthdr = {}
    for s in root.findall("struct"):
        m = re.fullmatch(r"EXTHDR_(\w+?)(\d+)", s.attrib["name"])
        if not m:
            continue
        bits = {}
        for f in s.findall("field"):
            if f.attrib["name"].startswith("has_"):
                if f.attrib["start"] != f.attrib["end"] or int(f.attrib["start"]) > 27:
                    raise SystemExit(f"{s.attrib['name']}.{f.attrib['name']}: one data bit, 0..27")
                bits[f.attrib["name"][4:]] = int(f.attrib["start"])
        exthdr.setdefault(m.group(1), {})[int(m.group(2))] = bits
    main = {}
    for s in streams:
        if "_EXT_" not in s.name:
            if not s.name.startswith("CMD_"):
                raise SystemExit(f"{s.name}: a main stream is named CMD_<type>")
            s.kind = s.name[4:]
            s.ext = []
            main[s.kind] = s
    for s in streams:
        if "_EXT_" in s.name:
            kind, ext = s.name[4:].split("_EXT_")
            hits = [(t, b[ext.lower()]) for t, b in exthdr.get(kind, {}).items() if ext.lower() in b]
            if kind not in main or len(hits) != 1:
                raise SystemExit(f"{s.name}: needs CMD_{kind} and one EXTHDR_{kind}<n>.has_{ext.lower()}")
            s.hdr_type, s.hdr_bit = hits[0]
            main[kind].ext.append(s)
    for kind, s in main.items():
        if kind not in exthdr or 0 not in exthdr[kind]:
            raise SystemExit(f"CMD_{kind}: no EXTHDR_{kind}0")
        s.exthdr = exthdr[kind]
        if max(s.exthdr) >= 8 or sorted(s.exthdr) != list(range(len(s.exthdr))):
            raise SystemExit(f"CMD_{kind}: EXTHDR types must be 0..n, n < 8")
        s.ext.sort(key=lambda x: (x.hdr_type, x.hdr_bit))
        lay_out(s)
    return [main[k] for k in sorted(main)]


def lay_out(s):
    off = HDR_BYTES
    for f in s.fields:
        off = (off + f.bytes - 1) // f.bytes * f.bytes
        f.offset = off
        off += f.bytes
    s.main_len = off
    every = s.fields + [f for e in s.ext for f in e.fields]
    names = [f.name for f in every]
    if len(set(names)) != len(names):
        raise SystemExit(f"CMD_{s.kind}: an extension field reuses a name")
    d = 0
    for f in sorted(every, key=lambda f: -f.bytes):
        f.dest = d
        d += f.bytes
    s.dest_size = (d + 7) // 8 * 8
    s.dest_pad = s.dest_size - d


SPDX_C = "/* SPDX-License-Identifier: MIT */"
GENERATED = "Generated by docs/uapi/gen_stream.py from {xml}. Do not edit."


def ctype(f):
    return "u64" if f.bits == 64 else "u32"


def kernel_h(streams, xml, prefix):
    guard = f"{prefix.upper()}_STREAM_DEFS_H"
    out = [SPDX_C, f"/* {GENERATED.format(xml=xml)} */", "", f"#ifndef {guard}", f"#define {guard}", ""]
    out += [f'#include "powervr_sgx_stream.h"', ""]
    for s in streams:
        for t, bits in sorted(s.exthdr.items()):
            mask = 0
            for b in bits.values():
                mask |= 1 << b
            out.append(f"#define {prefix.upper()}_STREAM_EXTHDR_{s.kind}{t}_VALID {mask:#x}U")
            for name, b in sorted(bits.items(), key=lambda x: x[1]):
                out.append(f"#define {prefix.upper()}_STREAM_EXTHDR_{s.kind}{t}_{name.upper()} BIT({b})")
    out.append("")
    for s in streams:
        every = s.fields + [f for e in s.ext for f in e.fields]
        out.append(f"/* CMD_{s.kind}, decoded. Extension fields not sent are zero. */")
        out.append(f"struct {prefix}_stream_{s.kind.lower()} {{")
        for f in sorted(every, key=lambda f: f.dest):
            out.append(f"\t{ctype(f)} {f.name};")
        if s.dest_pad:
            out.append(f"\tu32 _padding;")
        out.append("};")
        out.append("")
    for s in streams:
        out.append(f"extern const struct powervr_sgx_stream_cmd_defs {prefix}_stream_{s.kind.lower()}_defs;")
    out += ["", f"#endif /* {guard} */", ""]
    return "\n".join(out)


def def_entry(prefix, s, f):
    st = f"{prefix}_stream_{s.kind.lower()}"
    lines = [f"\t{{ .name = \"{f.name}\",",
             f"\t  .offset = offsetof(struct {st}, {f.name}),",
             f"\t  .size = {f.bytes},",
             f"\t  .check = POWERVR_SGX_STREAM_CHECK_{f.check.upper()},"]
    if f.check == "range":
        lines.append(f"\t  .min = {f.min:#x}, .max = {f.max:#x},")
        if f.limit:
            lines.append(f"\t  .limit = POWERVR_SGX_STREAM_LIMIT_{LIMITS[f.limit]},")
    if f.check == "mask":
        lines.append(f"\t  .mask = {f.mask:#010x},")
    if f.check == "addr":
        lines.append(f"\t  .heap = POWERVR_SGX_STREAM_HEAP_{HEAPS[f.heap]},")
        lines.append(f"\t  .align = {f.align},")
        if f.optional:
            lines.append("\t  .optional = true,")
        if f.extent in EXTENTS:
            lines.append(f"\t  .extent = POWERVR_SGX_STREAM_EXTENT_{EXTENTS[f.extent]},")
            if f.extent_field:
                lines.append(f"\t  .extent_field = offsetof(struct {st}, {f.extent_field}),")
        elif f.extent is not None:
            lines.append("\t  .extent = POWERVR_SGX_STREAM_EXTENT_BYTES,")
            lines.append(f"\t  .extent_bytes = {num(f.extent):#x},")
    lines[-1] = lines[-1] + " },"
    return lines


def kernel_c(streams, xml, prefix):
    out = [SPDX_C, f"/* {GENERATED.format(xml=xml)} */", "",
           "#include <linux/array_size.h>", "#include <linux/stddef.h>", "",
           f'#include "{prefix}_stream_defs.h"', ""]
    for s in streams:
        k = s.kind.lower()
        P = prefix.upper()
        out.append(f"static const struct powervr_sgx_stream_def {prefix}_stream_{k}_main[] = {{")
        for f in s.fields:
            out += def_entry(prefix, s, f)
        out += ["};", ""]
        for e in s.ext:
            name = e.name.split("_EXT_")[1].lower()
            out.append(f"static const struct powervr_sgx_stream_def {prefix}_stream_{k}_ext_{name}[] = {{")
            for f in e.fields:
                out += def_entry(prefix, s, f)
            out += ["};", ""]
        for t in sorted(s.exthdr):
            exts = [e for e in s.ext if e.hdr_type == t]
            if exts:
                out.append(f"static const struct powervr_sgx_stream_ext_def {prefix}_stream_{k}_ext{t}[] = {{")
                for e in exts:
                    name = e.name.split("_EXT_")[1].lower()
                    out += [f"\t{{ .fields = {prefix}_stream_{k}_ext_{name},",
                            f"\t  .nr_fields = ARRAY_SIZE({prefix}_stream_{k}_ext_{name}),",
                            f"\t  .header_mask = {P}_STREAM_EXTHDR_{s.kind}{t}_{name.upper()},",
                            f"\t  .quirk = {e.quirk} }},"]
                out += ["};", ""]
        out.append(f"static const struct powervr_sgx_stream_ext_header {prefix}_stream_{k}_ext_headers[] = {{")
        for t in sorted(s.exthdr):
            if any(e.hdr_type == t for e in s.ext):
                out += [f"\t{{ .ext_streams = {prefix}_stream_{k}_ext{t},",
                        f"\t  .nr_ext_streams = ARRAY_SIZE({prefix}_stream_{k}_ext{t}),",
                        f"\t  .valid_mask = {P}_STREAM_EXTHDR_{s.kind}{t}_VALID }},"]
            else:
                out.append(f"\t{{ .valid_mask = {P}_STREAM_EXTHDR_{s.kind}{t}_VALID }},")
        out += ["};", ""]
        out += [f"const struct powervr_sgx_stream_cmd_defs {prefix}_stream_{k}_defs = {{",
                f"\t.name = \"CMD_{s.kind}\",",
                f"\t.main = {prefix}_stream_{k}_main,",
                f"\t.nr_main = ARRAY_SIZE({prefix}_stream_{k}_main),",
                f"\t.main_len = {s.main_len},",
                f"\t.ext_headers = {prefix}_stream_{k}_ext_headers,",
                f"\t.nr_ext_headers = ARRAY_SIZE({prefix}_stream_{k}_ext_headers),",
                f"\t.dest_size = sizeof(struct {prefix}_stream_{k}),",
                "};", ""]
    return "\n".join(out)


def user_h(streams, xml):
    """A writer for the main streams. Extension streams are appended by hand
    after it, with csbgen's EXTHDR packers."""
    out = [SPDX_C, f"/* {GENERATED.format(xml=xml)} */", "",
           "#ifndef SGX_KMD_STREAM_PACK_H", "#define SGX_KMD_STREAM_PACK_H", "",
           "#include <stdint.h>", "#include <string.h>", "",
           "/* Little-endian hosts only: the GPU is only found next to x86 CPUs. */", ""]
    for s in streams:
        n = f"SGX_KMD_STREAM_CMD_{s.kind}"
        out.append(f"#define {n}_length {s.main_len}")
        for f in s.fields:
            out.append(f"#define {n}_{f.name.upper()}_offset {f.offset}")
        out.append(f"struct {n} {{")
        for f in s.fields:
            t = {"float": "uint32_t", "int": "int32_t"}.get(f.type, f"uint{f.bits}_t")
            if f.bits == 64:
                t = "uint64_t"
            out.append(f"\t{t} {f.name};")
        out.append("};")
        out += ["", "/* Writes the header and the main stream; returns its length in bytes. */",
                f"static inline uint32_t\n{n}_pack(void *restrict dst, const struct {n} *restrict v)",
                "{",
                "\tuint8_t *p = dst;",
                f"\tconst uint32_t hdr[2] = {{ {s.main_len}, 0 }};",
                "",
                f"\tmemset(p, 0, {s.main_len});",
                "\tmemcpy(p, hdr, sizeof(hdr));"]
        for f in s.fields:
            out.append(f"\tmemcpy(p + {f.offset}, &v->{f.name}, {f.bytes});")
        out += [f"\treturn {s.main_len};", "}", ""]
    out += ["#endif /* SGX_KMD_STREAM_PACK_H */", ""]
    return "\n".join(out)


def doc(streams):
    out = ["| stream | offset | field | bits | type | kernel check |", "|---|---|---|---|---|---|"]
    for s in streams:
        out.append(f"| `CMD_{s.kind}` | 0x00 | header: `length` = {s.main_len}, then a zero word | 64 | | exact |")
        for f in s.fields:
            out.append(f"| | {f.offset:#04x} | `{f.name}` | {f.bits} | {f.type} | {f.describe()} |")
        for e in s.ext:
            q = f", quirk {e.quirk}" if e.quirk else ""
            out.append(f"| `{e.name}` | ext {e.hdr_type}, bit {e.hdr_bit}{q} | | | | |")
            for f in e.fields:
                out.append(f"| | | `{f.name}` | {f.bits} | {f.type} | {f.describe()} |")
    return "\n".join(out)


def main():
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    mode, xml = sys.argv[1], pathlib.Path(sys.argv[2])
    streams = parse(xml)
    if mode == "kernel-h":
        sys.stdout.write(kernel_h(streams, xml.name, sys.argv[3]))
    elif mode == "kernel-c":
        sys.stdout.write(kernel_c(streams, xml.name, sys.argv[3]))
    elif mode == "user":
        sys.stdout.write(user_h(streams, xml.name))
    elif mode == "doc":
        print(doc(streams))
    elif mode in ("--check", "--write"):
        path = pathlib.Path(sys.argv[3])
        text = path.read_text()
        block = f"{BEGIN}\n{doc(streams)}\n{END}"
        if mode == "--write":
            pattern = re.escape(BEGIN) + r"\n(?:.*?\n)?" + re.escape(END)
            path.write_text(re.sub(pattern, lambda _: block, text, flags=re.S))
        elif block not in text:
            print(f"{path}: the stream table differs from {xml.name}", file=sys.stderr)
            return 1
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
